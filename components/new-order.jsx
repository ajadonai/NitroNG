// The K/M shorthand exists so a five-figure naira total fits a phone. It is a
// naira habit and does not survive conversion — a dollar total is already short,
// and compacting it would print "$0.00M" — so it applies to naira only.
function compactPrice(n, money, currency) {
  if (currency !== "NGN") return money(n);
  if (n >= 1_000_000) return `₦${(n / 1_000_000).toFixed(1).replace(/\.0$/, "")}M`;
  if (n >= 10_000) return `₦${(n / 1_000).toFixed(1).replace(/\.0$/, "")}K`;
  return money(n);
}

function getPresets(min, max) {
  const nice = [10, 25, 50, 100, 250, 500, 1000, 2500, 5000, 10000, 25000, 50000, 100000];
  const pool = nice.filter(v => v >= min && v <= max);
  if (!pool.length || pool[0] !== min) pool.unshift(min);
  if (pool[pool.length - 1] !== max) pool.push(max);
  if (pool.length <= 5) return pool;
  const step = (pool.length - 1) / 4;
  return [0, 1, 2, 3, 4].map(i => pool[Math.round(i * step)]);
}

function getRowPricePer1k(row, menu) {
  if (!menu?.groups) return 0;
  for (const g of menu.groups) {
    const tier = g.tiers.find(t2 => t2.id === row.tierId);
    if (tier) return tier.price;
  }
  return 0;
}

function normalizePriceUpdates(rows = []) {
  const updates = new Map();
  for (const row of rows) {
    const price = Number(row.currentPrice ?? (row.serverPrice != null ? row.serverPrice / 100 : 0));
    if (!Number.isFinite(price) || price <= 0) continue;
    // Namespaced, because a tier id and a public catalogue number are different
    // counters and would otherwise collide in the same Map.
    if (row.tierId) updates.set(`t${row.tierId}`, price);
    else if (row.catalogueId != null) updates.set(`c${row.catalogueId}`, price);
  }
  return updates;
}

function applyPriceUpdatesToCartRows(rows, priceRows = [], menuData = null) {
  const serverUpdates = normalizePriceUpdates(priceRows);
  let changed = false;
  const next = rows.map(row => {
    const key = row.tierId ? `t${row.tierId}` : row.catalogueId != null ? `c${row.catalogueId}` : null;
    const nextPrice = (key && serverUpdates.get(key)) || getRowPricePer1k(row, menuData);
    if (nextPrice > 0 && row.storedPricePer1k !== nextPrice) {
      changed = true;
      return { ...row, storedPricePer1k: nextPrice };
    }
    return row;
  });
  return changed ? next : rows;
}

function applyPriceUpdatesToMenu(menuData, priceRows = []) {
  if (!menuData?.groups) return menuData;
  const serverUpdates = normalizePriceUpdates(priceRows);
  if (serverUpdates.size === 0) return menuData;
  let changed = false;
  const groups = menuData.groups.map(group => {
    let groupChanged = false;
    const tiers = group.tiers.map(tier => {
      // The menu holds curated tiers only, so it asks for the tier key. The
      // full list is not in menuData at all — its rows keep the price they were
      // added with until the server says otherwise.
      const nextPrice = serverUpdates.get(`t${tier.id}`);
      if (nextPrice > 0 && tier.price !== nextPrice) {
        changed = true;
        groupChanged = true;
        return { ...tier, price: nextPrice };
      }
      return tier;
    });
    return groupChanged ? { ...group, tiers } : group;
  });
  return changed ? { ...menuData, groups } : menuData;
}

const CART_KEY = "nitro_bulk_cart_v1";
const CART_TTL = 86400000;

function loadCart() {
  try {
    const raw = localStorage.getItem(CART_KEY);
    if (!raw) return [];
    const { rows, savedAt } = JSON.parse(raw);
    if (Date.now() - savedAt > CART_TTL) { localStorage.removeItem(CART_KEY); return []; }
    return rows || [];
  } catch { return []; }
}
function saveCart(rows) {
  try { localStorage.setItem(CART_KEY, JSON.stringify({ rows, savedAt: Date.now() })); } catch {}
}

